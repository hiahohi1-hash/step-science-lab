// ─────────────────────────────────────────────
// 방법: "관리자 화면 알림" (8단계에서 텔레그램 대신 이 방법으로 정함)
//   1) 알림 내용을 데이터베이스 "알림 기록"에 저장
//   2) 열려 있는 화면들에 "새 알림이 있어요" 신호만 보냄 (번호만, 내용·학번·이름은 안 보냄)
//   3) 로그인한 관리자 화면이 그 신호를 받고, 서버에 내용을 물어봐서 컴퓨터 알림 창 + 소리로 보여 줌
// → 학생 정보가 학교 컴퓨터 밖으로 나가지 않습니다. 비용도, 가입도, 비밀 열쇠도 필요 없습니다.
//
// 나중에 다른 방법(예: 메신저)을 붙이고 싶으면 이 파일만 고치면 됩니다.
// ⚠ 문자 메시지·카카오 알림톡은 유료입니다. 붙이기 전에 요금을 꼭 확인하세요.
// ⚠ 외부 서비스를 붙이면 학번·이름이 학교 밖으로 나갑니다. 학교 개인정보 규정을 먼저 확인하세요.

const { now } = require('./clock');
const { broadcast } = require('./events');

// type: 알림 종류 (예: '반출', '승인 요청', '연장', '반납', '재구매 필요', '연체', '자동 취소', '곧 반납 기한')
// message: 관리자가 볼 글 (관리자 화면에서만 보임)
function notifyAdmin(db, type, message) {
  const info = db.prepare('INSERT INTO notifications (type, message, sent_at, success, error) VALUES (?, ?, ?, 1, NULL)')
    .run(type, message, now().toISOString());
  // 로그인 없이 누구나 받는 신호이므로 번호와 종류만 보냄 (내용은 관리자만 서버에 물어볼 수 있음)
  broadcast('admin-notice', { id: Number(info.lastInsertRowid) });
}

module.exports = { notifyAdmin };
